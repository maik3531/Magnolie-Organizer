#!/usr/bin/env python3
"""Reproduce the #791/#682 native source/resource compile and 31 JVM checks.

Uses previously downloaded official artifacts and their recorded SHA-256 values.
Does not download, install, sign, create a runnable APK, or contact a device.
The web projection must have been generated by the repository's project-web.cjs.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import subprocess
import tempfile
import xml.etree.ElementTree as ET


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repository', type=Path, default=here / 'Magnolie-Organizer')
    parser.add_argument('--dependencies', type=Path, default=here / 'tablet-build-dependencies')
    parser.add_argument('--output', type=Path, default=here / 'native-script-reproduction')
    args = parser.parse_args()
    repo = args.repository.resolve()
    deps = args.dependencies.resolve()
    output = args.output.resolve()
    root = repo / 'Magnolie-Organizer-Android-Tablet-Beta'
    output.mkdir(parents=True, exist_ok=True)
    run_dir = Path(tempfile.mkdtemp(prefix='run-', dir=output))
    expected = {}
    for name in ('maven-dependency-manifest.json', 'android-compile-dependency-manifest.json'):
        for row in json.loads((deps / name).read_text()):
            expected[row['file']] = row['sha256']
            if 'classes_file' in row:
                expected[row['classes_file']] = row['classes_sha256']
    expected['android-37.2.jar'] = json.loads((deps / 'android-platform-manifest.json').read_text())['android_jar_sha256']
    expected['aapt2-36'] = json.loads((deps / 'aapt2-manifest.json').read_text())['aapt2_sha256']
    for name, digest in expected.items():
        if sha256(deps / name) != digest:
            raise SystemExit(f'Artifact hash mismatch: {name}')
    # Only manifest-bound JARs enter the classpaths; arbitrary directory files do not.
    jars = sorted(deps / name for name in expected if name.endswith('.jar'))
    pure_jars = [path for path in jars if path.name != 'android-37.2.jar']

    def run(name: str, command: list[str | Path]) -> str:
        command = [str(value) for value in command]
        result = subprocess.run(command, text=True, capture_output=True, cwd=repo)
        text = '$ ' + shlex.join(command) + '\n' + result.stdout + result.stderr + f'\nexit={result.returncode}\n'
        (run_dir / (name + '.log')).write_text(text)
        if result.returncode:
            raise RuntimeError(f'{name} failed; see {run_dir / (name + ".log")}')
        return result.stdout + result.stderr

    aapt = deps / 'aapt2-36'
    platform = deps / 'android-37.2.jar'
    build = (root / 'app/build.gradle.kts').read_text()
    namespace = re.search(r'namespace\s*=\s*"([^"]+)"', build).group(1)
    min_sdk = re.search(r'minSdk\s*=\s*(\d+)', build).group(1)
    target_sdk = re.search(r'targetSdk\s*=\s*(\d+)', build).group(1)
    projection = root / 'app/build/generated/projection/res'
    if not (projection / 'values/strings.xml').is_file():
        raise SystemExit('Run the repository web projection before this source-compile probe.')
    resource_inputs = [root / 'app/src/main/AndroidManifest.xml']
    resource_inputs += sorted(path for base in (root / 'app/src/main/res', projection) for path in base.rglob('*') if path.is_file())
    resource_hashes = {str(path.relative_to(repo)): sha256(path) for path in resource_inputs}
    run('java-version', ['java', '-version'])
    run('resource-main', [aapt, 'compile', '--dir', root / 'app/src/main/res', '-o', run_dir / 'main-res.zip'])
    run('resource-projection', [aapt, 'compile', '--dir', projection, '-o', run_dir / 'projected-res.zip'])
    manifest = ET.parse(root / 'app/src/main/AndroidManifest.xml')
    manifest.getroot().set('package', namespace)  # Actual AGP namespace supplied to aapt2.
    manifest.write(run_dir / 'AndroidManifest.xml', encoding='utf-8', xml_declaration=True)
    run('resource-link', [aapt, 'link', '-I', platform, '--manifest', run_dir / 'AndroidManifest.xml',
        '--java', run_dir / 'generated', '--min-sdk-version', min_sdk, '--target-sdk-version', target_sdk,
        '--auto-add-overlay', '-R', run_dir / 'main-res.zip', '-R', run_dir / 'projected-res.zip',
        '-o', run_dir / 'resources-only.ap_'])
    resource_java = sorted((run_dir / 'generated').rglob('*.java'))
    if len(resource_java) != 1:
        raise SystemExit('Unexpected generated resource Java input count')
    classes = run_dir / 'classes'
    classes.mkdir()
    # This installed JDK has javac as a module, but no ct.sym for --release 17.
    # Generated R contains resource constants; compile its actual output to JVM17.
    run('resource-java', ['java', '-m', 'jdk.compiler/com.sun.tools.javac.Main', '-source', '17', '-target', '17',
        '-d', classes, *resource_java])
    sources = sorted((root / 'app/src/main/java').rglob('*.kt'))
    crypto = repo / 'magnolie-notes/app/src/main/java/io/gitlab/maik3531/magnolienotes/daten'
    sources += [crypto / name for name in ('DatenDateiKrypto.kt', 'DateiDauerhaft.kt')]
    source_hashes = {str(path.relative_to(repo)): sha256(path) for path in sources}
    base = root / 'app/src/main/java/io/gitlab/maik3531/magnolietabletbeta'
    tests = root / 'app/src/test/java/io/gitlab/maik3531/magnolietabletbeta'
    pure = [base / name for name in ('SystemImportPolicy.kt', 'SystemSourcePolicy.kt', 'SystemSourceBridge.kt', 'AttachmentLaunchPolicy.kt')]
    pure += [tests / name for name in ('SystemImportPolicyTest.kt', 'SystemSourcePolicyTest.kt', 'AttachmentLaunchPolicyTest.kt')]
    pure_hashes = {str(path.relative_to(repo)): sha256(path) for path in pure}
    native_cp = os.pathsep.join(str(path) for path in jars + [classes])
    pure_cp = os.pathsep.join(str(path) for path in pure_jars)
    test_classes = run_dir / 'test-classes'
    test_classes.mkdir()

    def compile_group(name: str, classpath: str, destination: Path, inputs: list[Path]) -> str:
        return run(name, ['java', '-cp', classpath, 'org.jetbrains.kotlin.cli.jvm.K2JVMCompiler', '-no-stdlib', '-no-reflect',
            '-jvm-target', '17', '-classpath', classpath, '-d', destination, *inputs])

    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
        jobs = [pool.submit(compile_group, 'product-kotlin', native_cp, classes, sources),
                pool.submit(compile_group, 'test-kotlin', pure_cp, test_classes, pure)]
        for job in jobs:
            job.result()
    junit = run('junit', ['java', '-cp', pure_cp + os.pathsep + str(test_classes), 'org.junit.runner.JUnitCore',
        'io.gitlab.maik3531.magnolietabletbeta.SystemImportPolicyTest',
        'io.gitlab.maik3531.magnolietabletbeta.SystemSourcePolicyTest',
        'io.gitlab.maik3531.magnolietabletbeta.AttachmentLaunchPolicyTest'])
    if 'OK (31 tests)' not in junit:
        raise SystemExit('Unexpected JVM test count/result')
    for mapping in (source_hashes, pure_hashes, resource_hashes):
        for path, digest in mapping.items():
            if sha256(repo / path) != digest:
                raise SystemExit(f'Input changed while compiling: {path}')
    receipt = {'result': 'passed', 'scriptSha256': sha256(Path(__file__)), 'kotlinSources': len(sources),
        'jvmTests': 31, 'javaResources': len(resource_java), 'androidApi': '37.2', 'aapt2': '36',
        'minSdk': int(min_sdk), 'targetSdk': int(target_sdk), 'jvmTarget': 17,
        'apkBuild': False, 'gradleFullBuild': False, 'nativeRuntimeTest': False,
        'sourceHashes': source_hashes, 'testInputHashes': pure_hashes, 'resourceInputHashes': resource_hashes,
        'dependencyHashes': expected, 'runDirectory': str(run_dir)}
    (output / 'receipt.json').write_text(json.dumps(receipt, indent=2) + '\n')
    print(json.dumps({key: value for key, value in receipt.items() if not key.endswith('Hashes')}, indent=2))


if __name__ == '__main__':
    main()
